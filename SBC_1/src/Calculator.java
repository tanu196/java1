
public class Calculator {
	
	public static void add(int a , int b) {
		int sum = a + b;
		System.out.println("" + a + "+" + b + "の計算結果は" + sum + "です");
	}
	
	
	
	public static void subtract(int a , int b){
		int dis = a - b;
		System.out.println("" + a + "-" +  b + "の計算結果は" + dis + "です");
	}
	
	
}
